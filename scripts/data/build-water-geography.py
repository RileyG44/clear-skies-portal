"""Rebuild the bundled Natural Earth land/ocean/inland-water mask (requires Pillow).
Natural Earth 1:10m is public domain: https://www.naturalearthdata.com/about/terms-of-use/
This is display geography, not a shoreline survey or an elevation source.
"""
import base64
import json
import math
from collections import defaultdict
from array import array
from pathlib import Path
import urllib.request
from PIL import Image, ImageDraw

REVISION = "ca96624a56bd078437bca8184e78163e5039ad19"
WIDTH, HEIGHT = 16384, 8192

def load(name):
    url = f"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{REVISION}/geojson/ne_10m_{name}.geojson"
    with urllib.request.urlopen(url) as response:
        return json.load(response)

image = Image.new("L", (WIDTH, HEIGHT), 1)
draw = ImageDraw.Draw(image)
def ring(points):
    return [((lon + 180) / 360 * WIDTH, (90 - lat) / 180 * HEIGHT) for lon, lat, *_ in points]

def paint(collection, fill, holes=False):
    for feature in collection["features"]:
        geometry = feature["geometry"]
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        for polygon in polygons:
            # Sample geographic cell centres with an even/odd scanline fill.
            # Pillow polygon filling rounds edges outward and can erase a bay
            # several cells wide. Intersections retain narrow marine coasts.
            rows = defaultdict(list)
            for boundary in (polygon[1:] if holes else polygon):
                points = ring(boundary)
                for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1]):
                    if y0 == y1:
                        continue
                    first = max(0, math.ceil(min(y0, y1) - .5))
                    end = min(HEIGHT, math.ceil(max(y0, y1) - .5))
                    for y in range(first, end):
                        rows[y].append(x0 + (y + .5 - y0) * (x1 - x0) / (y1 - y0))
            for y, crossings in rows.items():
                crossings.sort()
                for low, high in zip(crossings[::2], crossings[1::2]):
                    first = max(0, math.ceil(low - .5))
                    end = min(WIDTH, math.ceil(high - .5))
                    if end > first:
                        draw.line((first, y, end - 1, y), fill=fill)

land = load("land")
paint(land, 2, holes=True)  # Inland seas omitted from the lakes collection.
paint(land, 0)             # Restore land/islands while retaining interior water.
paint(load("lakes"), 2)
# Classes: 0 land, 1 ocean, 2 inland water. Two bits retain the original
# geographic spacing and 2048-square texture size using RGBA16UI (32 MiB).
planes = [image.point([255 if value == kind else 0 for value in range(256)])
          .convert("1", dither=Image.Dither.NONE).tobytes() for kind in (1, 2)]
spread = [sum(((value >> (7-i)) & 1) << (14-2*i) for i in range(8)) for value in range(256)]
packed = array("H", [0]) * (WIDTH // 8 * HEIGHT)
stride = WIDTH // 8
for y in range(HEIGHT):
    for x in range(stride):
        source = y * stride + x
        packed[((y // 4) * stride + x) * 4 + y % 4] = spread[planes[0][source]] | (spread[planes[1][source]] << 1)
encoded = bytearray()
start = 0
for index in range(1, len(packed) + 1):
    if index < len(packed) and packed[index] == packed[start]:
        continue
    encoded.extend((packed[start] & 255, packed[start] >> 8))
    count = index - start
    while count >= 128:
        encoded.append((count & 127) | 128)
        count >>= 7
    encoded.append(count)
    start = index
payload = base64.b64encode(encoded).decode("ascii")
root = Path(__file__).resolve().parents[2]
(root / "water-geography-data.js").write_text(
    "/* Generated by scripts/data/build-water-geography.py. Natural Earth 1:10m, public domain.\n"
    f" * Source revision {REVISION}; land/ocean/inland water; two bits per pixel; geographic cell-centre sampling, no erosion. */\n"
    "(function(root){const data=" + json.dumps(payload) + ";\n"
    "if(typeof module==='object'&&module.exports)module.exports=data;else root.CSPWaterGeographyData=data;\n"
    "})(typeof globalThis!=='undefined'?globalThis:this);\n"
)
print(f"{len(packed)*2:,} decoded bytes; {len(payload):,} base64 bytes")
