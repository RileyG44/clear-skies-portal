'use strict';
/* Writes ui-icons.js: every vendor/icons/*.svg as a data URI, so the shell's
   controls arrive with their icons instead of waiting on image requests.
   Run `npm run ui-icons` after changing vendor/icons; test-ui-icons.js fails
   if the two drift apart. */
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..'),dir=path.join(root,'vendor','icons');
function source(){
  const icons={};
  for(const file of fs.readdirSync(dir).filter(f=>f.endsWith('.svg')).sort())
    icons[file.slice(0,-4)]='data:image/svg+xml,'+encodeURIComponent(fs.readFileSync(path.join(dir,file),'utf8').trim());
  return '/* Generated by scripts/build-ui-icons.js from vendor/icons. Do not edit. */\n'+
    'window.CSPIcons=Object.freeze('+JSON.stringify(icons,null,0).replace(/","/g,'",\n"')+');\n';
}
if(require.main===module)fs.writeFileSync(path.join(root,'ui-icons.js'),source());
module.exports={source};
