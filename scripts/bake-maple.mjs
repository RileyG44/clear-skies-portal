// Grows the landing page's maple once and writes it, packed, to
// landing/maple-tree.js, so visitors' browsers (phones above all) skip the growth.
// Run after changing landing/maple-growth.js: node scripts/bake-maple.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { growMaple, packMaple, TREE, TREE_SEED } from "../landing/maple-growth.js";

const seed = TREE_SEED;
const B = packMaple(growMaple(seed, TREE), seed, TREE);
const out = fileURLToPath(new URL("../landing/maple-tree.js", import.meta.url));
writeFileSync(out, "// Generated by scripts/bake-maple.mjs from maple-growth.js. Do not edit.\n" +
  "export const BAKED = " + JSON.stringify(B) + ";\n");
console.log(`baked ${B.n} nodes, ${B.knots.length} knots -> landing/maple-tree.js`);
