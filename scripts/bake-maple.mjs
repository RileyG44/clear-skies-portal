// Grows each of the landing page's maples once and writes it, packed, to its own module
// (landing/maple-tree.js for the bigleaf, landing/maple-tree-vine.js for the vine maple),
// so visitors' browsers (phones above all) skip the growth, and download only the tree
// they are shown. Run after changing landing/maple-growth.js: node scripts/bake-maple.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { growMaple, packMaple } from "../landing/maple-growth.js";
import { SPECIES } from "../landing/maple-species.js";

for (const sp of Object.values(SPECIES)) {
  const B = packMaple(growMaple(sp.seed, sp.growth), sp.seed, sp.growth);
  const out = fileURLToPath(new URL("../landing/" + sp.bakeFile, import.meta.url));
  writeFileSync(out, "// Generated by scripts/bake-maple.mjs from maple-growth.js. Do not edit.\n" +
    "export const BAKED = " + JSON.stringify(B) + ";\n");
  console.log(`${sp.id}: baked ${B.n} nodes, ${B.knots.length} knots -> landing/${sp.bakeFile}`);
}
