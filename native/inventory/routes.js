#!/usr/bin/env node
/* Phase 0 route inventory (docs/native/ARCHITECTURE.md §5): every route the
   Node engine answers, who calls it, and which native component takes it
   over. LocalEngine must answer each one with the same method, status,
   headers and body before the WebView map can run without the Dell.

   node native/inventory/routes.js            rewrites docs/native/ROUTES.md
   node native/inventory/routes.js --check    exits 1 if the file is stale  */
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const OUT = path.join(ROOT, "docs", "native", "ROUTES.md");

/* Module order is server.js's Object.assign order; later keys win. */
const MODULES = [
  ["terrain", "csk-core::sources + raster (USGS, national, overview, fabric)"],
  ["oregon", "csk-core::sources (Oregon DOGAMI)"],
  ["dnr-routes", "csk-core::sources + jobs (WA DNR catalogue, ingest, exports)"],
  ["downloads", "csk-core::jobs + store (offline areas)"],
  ["proxies", "csk-core::sources (small proxies)"],
  ["snapshot", "csk-core::raster (snapshot validation and encode)"],
  ["markup-store", "csk-sync (local markup, then CloudKit)"],
];

function serverFacts(){
  const src = fs.readFileSync(path.join(ROOT, "server.js"), "utf8");
  const post = /const POST_ONLY=new Set\(\[([\s\S]*?)\]\)/.exec(src);
  if(!post) throw new Error("server.js: POST_ONLY not found; update native/inventory/routes.js");
  const postOnly = new Set([...post[1].matchAll(/"([^"]+)"/g)].map(m => m[1]));
  if(!/"\/api\/health":/.test(src)) throw new Error("server.js: /api/health not found");
  return {postOnly};
}

/* Client code that names a route literally. Routes built from pieces at
   run time show as "none found" and are reviewed by hand. */
function clientFiles(){
  const files = [];
  const add = dir => { for(const f of fs.readdirSync(path.join(ROOT, dir))){
    if(!/\.(m?js|html)$/.test(f) || /^test-/.test(f) || (dir === "." && /^(server|electron-builder.*)\.js$/.test(f))) continue;
    files.push(path.posix.join(dir, f).replace(/^\.\//, ""));
  } };
  add("."); add("app"); add("ios/Resources");
  return files.map(f => ({f, text: fs.readFileSync(path.join(ROOT, f), "utf8")}));
}

function build(){
  const {postOnly} = serverFacts();
  const routes = new Map();
  for(const [mod, owner] of MODULES){
    for(const key of Object.keys(require(path.join(ROOT, "engine", mod + ".js")).routes)) routes.set(key, {mod, owner});
  }
  routes.set("/api/health", {mod: "server.js", owner: "LocalEngine (health and feature flags)"});
  const files = clientFiles();
  const rows = [...routes].sort(([a], [b]) => a.localeCompare(b)).map(([route, {mod, owner}]) => {
    const needle = route.endsWith("/") ? route : route;
    const exact = new RegExp(needle.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&") + (route.endsWith("/") ? "" : "(?![\\w/-])"));
    const callers = files.filter(({text}) => exact.test(text)).map(({f}) => "`" + f + "`");
    return `| \`${route}\` | ${route.endsWith("/") ? "prefix" : "exact"} | ${postOnly.has(route) ? "POST" : "GET" + (mod === "markup-store" || route === "/api/snapshot/image" ? ", POST" : "")} | \`${mod === "server.js" ? mod : "engine/" + mod + ".js"}\` | ${owner} | ${callers.join(", ") || "none found (built at run time; review)"} |`;
  });
  return `# Engine route inventory

Generated by \`native/inventory/routes.js\` from the route tables
\`server.js\` assembles; \`test-native-inventory.js\` fails when it is stale.
Do not edit the table by hand.

Each route below must be answered by \`LocalEngine\` (method, status, headers
and body) before the WebView map runs with no Dell (phase 2 for USGS, phase 3
for the rest, phase 6a for the full set). "Owner" is the component in
docs/native/ARCHITECTURE.md §4.1 that takes it over. Methods are what the
engine accepts; markup and snapshot routes dispatch on the method inside the
handler.

${routes.size} routes.

| Route | Match | Methods | Today | Native owner | Client callers |
|---|---|---|---|---|---|
${rows.join("\n")}
`;
}

if(require.main === module){
  const text = build();
  if(process.argv.includes("--check")){
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if(now !== text){ console.error("docs/native/ROUTES.md is stale: run node native/inventory/routes.js"); process.exit(1) }
    console.log("route inventory current");
  }else{
    fs.mkdirSync(path.dirname(OUT), {recursive: true});
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)}`);
  }
  process.exit(0);
}
module.exports = {build, OUT};
